"""The contract every engine implements, so the runner can treat them identically."""
from __future__ import annotations

import json
from abc import ABC, abstractmethod
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from ..timing import StageTimer

SAMPLE_RATE = 24_000
TOKENS_PER_SECOND = 50


@dataclass(frozen=True)
class Voice:
    name: str
    codes: np.ndarray  # int32 reference codes, 50 per second
    text: str  # transcript of the reference clip
    wav_path: Path  # original recording, used for speaker similarity

    @property
    def seconds(self) -> float:
        return len(self.codes) / TOKENS_PER_SECOND


@dataclass(frozen=True)
class Request:
    text: str
    voice: Voice
    seed: int
    stream: bool


@dataclass
class Result:
    audio: np.ndarray
    tokens: np.ndarray  # generated speech codes (excluding the reference)
    prompt_tokens: int
    stop_reason: str  # "eos" | "max_tokens" | "context"
    timer: StageTimer
    sample_rate: int = SAMPLE_RATE
    extra: dict = field(default_factory=dict)

    @property
    def audio_seconds(self) -> float:
        return len(self.audio) / self.sample_rate


class Engine(ABC):
    """Lifecycle: ``load()`` once, ``run()`` many times, ``close()``."""

    name: str = "engine"

    def __init__(self, settings: dict) -> None:
        self.settings = settings

    @abstractmethod
    def load(self) -> None: ...

    @abstractmethod
    def synthesize(self, req: Request, timer: StageTimer) -> Result:
        """Whole-clip synthesis. Must call ``timer.mark_chunk`` once with the full audio."""

    @abstractmethod
    def stream(self, req: Request, timer: StageTimer) -> Iterator[np.ndarray]:
        """Yield audio chunks; the caller marks chunk arrival times."""

    def decode_full(self, tokens: np.ndarray) -> np.ndarray:
        """Decode tokens in one pass, no watermark (stream-fidelity reference). Optional."""
        raise NotImplementedError

    def stream_tokens(self) -> np.ndarray:
        """Tokens generated by the last ``stream`` call."""
        return getattr(self, "_last_stream_tokens", np.zeros(0, np.int32))

    def describe(self) -> dict:
        return {"engine": self.name, **self.settings}

    def close(self) -> None:  # noqa: B027 - optional hook
        pass

    def run(self, req: Request) -> Result:
        timer = StageTimer()
        if not req.stream:
            result = self.synthesize(req, timer)
            timer.finish()
            return result
        pieces = []
        for chunk in self.stream(req, timer):
            timer.mark_chunk(len(chunk))
            pieces.append(chunk)
        timer.finish()
        audio = np.concatenate(pieces) if pieces else np.zeros(0, np.float32)
        info = getattr(self, "_last_stream_info", {})
        return Result(
            audio=audio.astype(np.float32),
            tokens=self.stream_tokens(),
            prompt_tokens=info.get("prompt_tokens", 0),
            stop_reason=info.get("stop_reason", "eos"),
            timer=timer,
            extra=info.get("extra", {}),
        )


# The neutts 1.4.1 wheel ships only some voices (emily, paul, sophie, steven) and no
# recordings, which speaker similarity needs. The git repository has all of them, so
# voices are fetched from one pinned commit and checked against known hashes.
SAMPLES_COMMIT = "ac69851f28fc63a487917e7c2e27f0d75c759cba"
SAMPLES_URL = f"https://raw.githubusercontent.com/neuphonic/neutts/{SAMPLES_COMMIT}/samples"
SAMPLES_SHA256 = {
    "jo.pt": "ced66c5add5b35d920f685370d9bb1bc3faae16e6b9f98e4b9b95c59c628fe6e",
    "jo.txt": "8b3c68273b0caceb71b78aaaf9482ad33afd27b0d2fe0eab37d35e06236bd5f3",
    "jo.wav": "f789bc3799e64675a6324a978a3fffb0dd7850739d232cbe3d4bbbbc9973a314",
    "dave.pt": "6d3465d01ec65cb421ff2c1803c56ff91b9502b9303b3846989f04119523f361",
    "dave.txt": "2b94a10f7bc2e181e29fa400267771bbc8f258e36ec19846607864906c4cd9fa",
    "dave.wav": "6c6b0e0c730ad0eddb53f321bd571ba55c3ed7ac4422610a17de7f62675c09e9",
}


def fetch_samples(names: list[str], dest: Path) -> Path:
    """Download ``<name>.pt/.txt/.wav`` from the pinned NeuTTS commit (once)."""
    import hashlib
    import urllib.request

    dest.mkdir(parents=True, exist_ok=True)
    for name in names:
        for ext in ("pt", "txt", "wav"):
            fname = f"{name}.{ext}"
            path = dest / fname
            if not path.exists():
                tmp = path.with_suffix(path.suffix + ".part")
                urllib.request.urlretrieve(f"{SAMPLES_URL}/{fname}", tmp)
                tmp.rename(path)
            want = SAMPLES_SHA256.get(fname)
            if want and hashlib.sha256(path.read_bytes()).hexdigest() != want:
                path.unlink()
                raise ValueError(f"{fname}: checksum mismatch against neutts@{SAMPLES_COMMIT[:10]}")
    return dest


def find_samples_dir(names: list[str] | None = None) -> Path:
    """Directory holding ``<name>.pt/.txt/.wav`` for every requested voice: the
    neutts wheel or a checkout if complete, otherwise the pinned download."""
    import importlib.util

    from .components import CACHE_DIR

    names = names or ["jo"]
    spec = importlib.util.find_spec("neutts")
    candidates = []
    if spec and spec.submodule_search_locations:
        pkg = Path(next(iter(spec.submodule_search_locations)))
        candidates += [pkg / "samples", pkg.parent / "samples"]
    candidates.append(Path.cwd() / "samples")
    for c in candidates:
        if all((c / f"{n}.{ext}").exists() for n in names for ext in ("pt", "txt", "wav")):
            return c
    return fetch_samples(names, CACHE_DIR / "samples")


def load_voice(name_or_dir: str, cache_dir: Path) -> Voice:
    """Load a prepared voice (``<cache>/<name>.npy/.txt/.json``)."""
    base = cache_dir / name_or_dir
    meta = json.loads(base.with_suffix(".json").read_text())
    return Voice(
        name=name_or_dir,
        codes=np.load(base.with_suffix(".npy")).astype(np.int32),
        text=base.with_suffix(".txt").read_text().strip(),
        wav_path=Path(meta["wav"]),
    )


def prepare_voices(names: list[str], cache_dir: Path, samples_dir: Path | None = None) -> list[Path]:
    """Convert NeuTTS ``.pt`` reference codes to ``.npy`` once, in the parent process, so
    benchmark workers never need torch just to read a voice."""
    import torch

    samples_dir = samples_dir or find_samples_dir(names)
    cache_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name in names:
        src = samples_dir / name
        codes = torch.load(src.with_suffix(".pt"), map_location="cpu")
        codes = np.asarray(codes.cpu().numpy() if hasattr(codes, "cpu") else codes, dtype=np.int32).reshape(-1)
        np.save(cache_dir / f"{name}.npy", codes)
        (cache_dir / f"{name}.txt").write_text(src.with_suffix(".txt").read_text().strip() + "\n")
        (cache_dir / f"{name}.json").write_text(json.dumps({"wav": str(src.with_suffix(".wav").resolve())}))
        written.append(cache_dir / f"{name}.npy")
    return written
